package com.cashmath.app.service

import android.graphics.Color
import android.graphics.Paint
import android.graphics.pdf.PdfDocument
import com.cashmath.app.data.TransactionEntity
import com.cashmath.app.data.TransactionType
import com.cashmath.app.parser.DateTimeUtils
import java.io.File
import java.io.FileOutputStream
import java.util.Locale

object PdfReportGenerator {
    fun generatePdf(
        bookName: String,
        dateRange: String,
        transactions: List<TransactionEntity>,
        totalIn: Double,
        totalOut: Double,
        file: File,
        businessName: String = "CashMath Business",
        gstin: String? = null,
        phone: String? = null,
        address: String? = null
    ): File {
        val pdfDocument = PdfDocument()
        val paint = Paint()
        val titlePaint = Paint().apply {
            color = Color.BLACK
            textSize = 18f
            isFakeBoldText = true
        }
        val headerPaint = Paint().apply {
            color = Color.DKGRAY
            textSize = 11f
        }
        val textPaint = Paint().apply {
            color = Color.BLACK
            textSize = 10f
        }
        val tableHeaderPaint = Paint().apply {
            color = Color.BLACK
            textSize = 10f
            isFakeBoldText = true
        }

        var pageNumber = 1
        var pageInfo = PdfDocument.PageInfo.Builder(595, 842, pageNumber).create()
        var page = pdfDocument.startPage(pageInfo)
        var canvas = page.canvas
        var y = 40f

        // Header
        canvas.drawText(businessName, 40f, y, titlePaint)
        y += 20f

        val detailsLine = listOfNotNull(
            phone?.let { "Phone: $it" },
            gstin?.let { "GSTIN: $it" }
        ).joinToString("  |  ")

        if (detailsLine.isNotBlank()) {
            canvas.drawText(detailsLine, 40f, y, headerPaint)
            y += 15f
        }
        if (!address.isNullOrBlank()) {
            canvas.drawText(address, 40f, y, headerPaint)
            y += 15f
        }

        canvas.drawText("Book: $bookName  |  Period: $dateRange", 40f, y, headerPaint)
        y += 25f

        // Summary Box
        paint.color = Color.LTGRAY
        canvas.drawRect(40f, y, 555f, y + 60f, paint)
        y += 20f
        canvas.drawText("Total Cash In: +₹${String.format(Locale.getDefault(), "%.2f", totalIn)}", 60f, y, tableHeaderPaint)
        y += 20f
        canvas.drawText("Total Cash Out: -₹${String.format(Locale.getDefault(), "%.2f", totalOut)}", 60f, y, tableHeaderPaint)
        y += 20f
        val net = totalIn - totalOut
        canvas.drawText("Net Balance: ₹${String.format(Locale.getDefault(), "%.2f", net)}", 60f, y, tableHeaderPaint)
        y += 40f

        // Table Header
        canvas.drawText("Date", 40f, y, tableHeaderPaint)
        canvas.drawText("Particulars", 120f, y, tableHeaderPaint)
        canvas.drawText("Category", 280f, y, tableHeaderPaint)
        canvas.drawText("In (+)", 420f, y, tableHeaderPaint)
        canvas.drawText("Out (-)", 500f, y, tableHeaderPaint)
        y += 10f
        canvas.drawLine(40f, y, 555f, y, paint)
        y += 20f

        // Transactions
        transactions.forEach { tx ->
            if (y > 780f) {
                pdfDocument.finishPage(page)
                pageNumber++
                pageInfo = PdfDocument.PageInfo.Builder(595, 842, pageNumber).create()
                page = pdfDocument.startPage(pageInfo)
                canvas = page.canvas
                y = 40f
            }

            val dateTime = DateTimeUtils.formatTransactionTime(tx.transactionTimestamp)
            val date = dateTime.split(",")[0]
            
            canvas.drawText(date, 40f, y, textPaint)
            
            val party = tx.partyName ?: "No Name"
            val particulars = if (party.length > 25) party.substring(0, 22) + "..." else party
            canvas.drawText(particulars, 120f, y, textPaint)
            
            canvas.drawText(tx.category ?: "General", 280f, y, textPaint)
            
            if (tx.type == TransactionType.INCOME) {
                canvas.drawText("₹${String.format(Locale.getDefault(), "%.2f", tx.amount)}", 420f, y, textPaint)
            } else {
                canvas.drawText("₹${String.format(Locale.getDefault(), "%.2f", tx.amount)}", 500f, y, textPaint)
            }
            
            y += 20f
        }

        // Footer & Watermark
        y = (y + 30f).coerceAtMost(750f)
        canvas.drawLine(40f, y, 555f, y, headerPaint)
        y += 15f
        canvas.drawText("Generated by CashMath - Smart Digital Ledger", 40f, y, headerPaint)

        pdfDocument.finishPage(page)

        FileOutputStream(file).use { out ->
            pdfDocument.writeTo(out)
        }
        pdfDocument.close()
        
        return file
    }
}
